#!/bin/bash

SUBNET="172.16.20"

echo "Опрос подсети $SUBNET.0/24..."

# Запускаем параллельный ping (или попытку подключения) для заполнения таблицы ядра
for i in {1..254}; do
  ping -c 1 -W 1 "$SUBNET.$i" &> /dev/null &
done

# Ждем 2 секунды, пока пройдут фоновые запросы
wait

echo "Найденные устройства в сети (IP и MAC):"
# Читаем файл ядра, пропускаем заголовок и записи с нулевым MAC-адресом (00:00:00:00:00:00)
awk '$4 != "00:00:00:00:00:00" && NR > 1 {print $1 "\t" $4}' /proc/net/arp

